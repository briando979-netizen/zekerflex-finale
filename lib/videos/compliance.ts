import { prisma } from "@/lib/prisma";
import * as crypto from "crypto";

export interface WatermarkConfig {
  enabled: boolean;
  position: "top-left" | "top-right" | "bottom-left" | "bottom-right" | "center";
  opacity: number; // 0-1
  scale: number; // 0.1-1.0
  text?: string;
  logoUrl?: string;
}

export interface CaptionConfig {
  required: boolean;
  languages: string[];
  autoGenerate: boolean;
  provider?: "openai" | "aws" | "google" | "local";
}

export interface ComplianceReport {
  videoId: string;
  watermarkEnabled: boolean;
  captionsEnabled: boolean;
  gdprCompliant: boolean;
  dataRetention: {
    viewsRetainedDays: number;
    engagementRetainedDays: number;
  };
  consentTracking: {
    requiresConsent: boolean;
    consentCollected: number;
    consentRate: number;
  };
}

// Add watermark to video metadata
export async function enableWatermark(
  videoId: string,
  config: WatermarkConfig,
): Promise<void> {
  await prisma.video.update({
    where: { id: videoId },
    data: {
      watermarkEnabled: config.enabled,
    },
  });
}

// Enable captions for video
export async function enableCaptions(
  videoId: string,
  config: CaptionConfig,
): Promise<void> {
  // Update subtitles metadata
  const video = await prisma.video.findUnique({
    where: { id: videoId },
    select: { subtitles: true },
  });

  if (!video) throw new Error("Video not found");

  const subtitles = Array.isArray(video.subtitles) ? video.subtitles : [];

  for (const lang of config.languages) {
    if (!subtitles.some((s: any) => s.language === lang)) {
      subtitles.push({
        language: lang,
        url: `/captions/${videoId}_${lang}.vtt`,
        autoGenerated: config.autoGenerate,
      });
    }
  }

  await prisma.video.update({
    where: { id: videoId },
    data: {
      captionsRequired: config.required,
      subtitles: subtitles,
    },
  });
}

// Mark video as GDPR compliant
export async function markGdprCompliant(videoId: string, compliant: boolean = true): Promise<void> {
  await prisma.video.update({
    where: { id: videoId },
    data: { gdprCompliant: compliant },
  });
}

// Generate anonymous viewer ID (hash-based)
export function generateAnonymousViewerId(userAgent: string, ip: string): string {
  const combined = `${userAgent}:${ip}`;
  return crypto
    .createHash("sha256")
    .update(combined)
    .digest("hex")
    .substring(0, 16);
}

// Check GDPR compliance for video
export async function checkGdprCompliance(videoId: string): Promise<ComplianceReport> {
  const video = await prisma.video.findUnique({
    where: { id: videoId },
    select: {
      watermarkEnabled: true,
      captionsRequired: true,
      gdprCompliant: true,
      subtitles: true,
    },
  });

  if (!video) throw new Error("Video not found");

  const views = await prisma.videoView.findMany({
    where: { videoId },
  });

  const anonymousViews = views.filter((v) => !v.userId).length;
  const consentRate = views.length > 0 ? (anonymousViews / views.length) * 100 : 0;

  return {
    videoId,
    watermarkEnabled: video.watermarkEnabled,
    captionsEnabled: Array.isArray(video.subtitles) && video.subtitles.length > 0,
    gdprCompliant: video.gdprCompliant,
    dataRetention: {
      viewsRetainedDays: 90,
      engagementRetainedDays: 90,
    },
    consentTracking: {
      requiresConsent: true,
      consentCollected: views.filter((v) => v.userId).length,
      consentRate,
    },
  };
}

// Purge old analytics data (GDPR right to be forgotten)
export async function purgeOldAnalytics(videoId: string, retentionDays: number = 90): Promise<{ purged: number }> {
  const cutoffDate = new Date(Date.now() - retentionDays * 24 * 60 * 60 * 1000);

  // Delete old views
  const deletedViews = await prisma.videoView.deleteMany({
    where: {
      videoId,
      createdAt: { lt: cutoffDate },
    },
  });

  // Delete old engagements
  const deletedEngagements = await prisma.videoEngagement.deleteMany({
    where: {
      videoId,
      createdAt: { lt: cutoffDate },
    },
  });

  return { purged: deletedViews.count + deletedEngagements.count };
}

// Delete all user data (right to erasure)
export async function deleteUserData(userId: string): Promise<{ purged: number }> {
  // Delete user views
  const deletedViews = await prisma.videoView.deleteMany({
    where: { userId },
  });

  // Delete user engagements
  const deletedEngagements = await prisma.videoEngagement.deleteMany({
    where: { userId },
  });

  return { purged: deletedViews.count + deletedEngagements.count };
}

// Export user data (right to access)
export async function exportUserData(userId: string): Promise<{
  views: any[];
  engagements: any[];
}> {
  const [views, engagements] = await Promise.all([
    prisma.videoView.findMany({
      where: { userId },
    }),
    prisma.videoEngagement.findMany({
      where: { userId },
    }),
  ]);

  return { views, engagements };
}

